'use strict';
const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('kb', {
  root: process.env.KB_ROOT || '',
  tree: () => ipcRenderer.invoke('kb:tree'),
  vaultState: () => ipcRenderer.invoke('kb:vaultState'),
  whoami: () => ipcRenderer.invoke('kb:whoami'),
  lastCommit: (rel) => ipcRenderer.invoke('kb:lastCommit', rel),
  chooseVault: () => ipcRenderer.invoke('kb:chooseVault'),
  read: (rel) => ipcRenderer.invoke('kb:read', rel),
  save: (rel, text, mtime) => ipcRenderer.invoke('kb:save', { rel, text, mtime }),
  complete: (kind, q) => ipcRenderer.invoke('kb:complete', { kind, q }),
  backlinks: (rel) => ipcRenderer.invoke('kb:backlinks', rel),
  search: (q, limit) => ipcRenderer.invoke('kb:search', { q, limit }),
  searchQuery: (q, limit) => ipcRenderer.invoke('kb:searchQuery', { q, limit }),
  setTitle: (t) => ipcRenderer.invoke('kb:setTitle', t),
  setDirty: (d) => ipcRenderer.send('kb:dirty', !!d),
  forceClose: () => ipcRenderer.invoke('kb:forceClose'),
  onSaveAndClose: (cb) => ipcRenderer.on('kb:save-and-close', () => cb()),
  image: (target, fromRel) => ipcRenderer.invoke('kb:image', { target, fromRel }),
  plugins: () => ipcRenderer.invoke('kb:plugins'),
  pluginCode: (name) => ipcRenderer.invoke('kb:pluginCode', name),
  assetUrl: (target, fromRel) => ipcRenderer.invoke('kb:assetUrl', { target, fromRel }),
  check: (rel) => ipcRenderer.invoke('kb:check', rel),
  peek: (target, fromRel) => ipcRenderer.invoke('kb:peek', { target, fromRel }),
  openWindow: (rel) => ipcRenderer.invoke('kb:openWindow', rel),
  windowState: () => ipcRenderer.invoke('kb:windowState'),
  windowCount: () => ipcRenderer.invoke('kb:windowCount'),
  openExternal: (url) => ipcRenderer.invoke('kb:openExternal', url),
  entryTags: (rel, field) => ipcRenderer.invoke('kb:entryTags', { rel, field }),
  setEntryTags: (rel, field, tags) => ipcRenderer.invoke('kb:setEntryTags', { rel, field, tags }),
  propHistory: (rel, field) => ipcRenderer.invoke('kb:propHistory', { rel, field }),
  tagSearch: (tag) => ipcRenderer.invoke('kb:tagSearch', { tag }),
  copy: (text) => ipcRenderer.invoke('kb:copy', text),
  clipboard: () => ipcRenderer.invoke('kb:clipboard'),
  onShortcut: (cb) => ipcRenderer.on('kb:shortcut', (_e, k) => cb(k)),
  welcome: (lang, id) => ipcRenderer.invoke('kb:welcome', lang, id),
  snapAuto: (url) => ipcRenderer.invoke('kb:snapAuto', url),
  snapList: (url) => ipcRenderer.invoke('kb:snapList', url),
  snapGet: (id) => ipcRenderer.invoke('kb:snapGet', id),
  snapSave: (data) => ipcRenderer.invoke('kb:snapSave', data),
  snapUrl: (id) => ipcRenderer.invoke('kb:snapUrl', id),
  webCookies: (url) => ipcRenderer.invoke('kb:webCookies', url),
  webClear: () => ipcRenderer.invoke('kb:webClear'),
  rename: (from, to) => ipcRenderer.invoke('kb:rename', { from, to }),
  commands: () => ipcRenderer.invoke('kb:commands'),
  run: (payload) => ipcRenderer.invoke('kb:run', payload),
});
