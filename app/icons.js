export function svgIcon(name, extraClass) {
  const d = ICONS[name];
  if (!d) return '';
  return '<svg class="icon' + (extraClass ? ' ' + extraClass : '') + '" viewBox="0 0 24 24" aria-hidden="true" focusable="false"><path d="' + d + '"/></svg>';
}

export function mountIcons(root) {
  const scope = root || document;
  for (const el of scope.querySelectorAll('[data-icon]')) {
    el.innerHTML = svgIcon(el.getAttribute('data-icon'));
  }
}
